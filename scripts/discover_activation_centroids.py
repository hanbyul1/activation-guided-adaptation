def resolve_device(requested: str) -> torch.device:
    requested = requested.lower()
    if requested == "auto":
        if torch.cuda.is_available():
            return torch.device("cuda")
        if getattr(torch.backends, "mps", None) and torch.backends.mps.is_available():
            return torch.device("mps")
        return torch.device("cpu")

    device = torch.device(requested)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA was requested but is not available.")
    if device.type == "mps":
        if not getattr(torch.backends, "mps", None):
            raise RuntimeError("MPS was requested but this PyTorch build lacks MPS.")
        if not torch.backends.mps.is_available():
            raise RuntimeError("MPS was requested but is not available.")
    return device


def resolve_dtype(name: str, device: torch.device) -> torch.dtype:
    name = name.lower()
    mapping = {
        "float32": torch.float32,
        "fp32": torch.float32,
        "float16": torch.float16,
        "fp16": torch.float16,
        "bfloat16": torch.bfloat16,
        "bf16": torch.bfloat16,
    }
    if name not in mapping:
        raise ValueError(f"Unsupported dtype: {name}")

    dtype = mapping[name]
    if device.type == "cpu" and dtype == torch.float16:
        LOGGER.warning("float16 on CPU is unsupported/slow; using float32.")
        return torch.float32
    if device.type == "mps" and dtype == torch.bfloat16:
        LOGGER.warning("bfloat16 on MPS is not consistently supported; using float16.")
        return torch.float16
    return dtype


def safe_float(value: Any) -> float:
    result = float(value)
    if not math.isfinite(result):
        return 0.0
    return result


