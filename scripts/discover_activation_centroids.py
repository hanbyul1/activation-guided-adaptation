def validate_arguments(args: argparse.Namespace) -> None:
    if args.batch_size < 1:
        raise ValueError("--batch-size must be at least 1.")
    if args.top_k_layers < 1:
        raise ValueError("--top-k-layers must be at least 1.")
    if not 0.0 < args.probe_validation_fraction < 1.0:
        raise ValueError(
            "--probe-validation-fraction must be strictly between 0 and 1."
        )
    if not 0.0 <= args.minimum_balanced_accuracy <= 1.0:
        raise ValueError(
            "--minimum-balanced-accuracy must be in [0, 1]."
        )
    if args.limit is not None and args.limit < 2:
        raise ValueError("--limit must be at least 2.")


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_argument_parser()
    args = parser.parse_args(argv)
    configure_logging(args.verbose)
    validate_arguments(args)

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    ensure_output_dir(args.output_dir, args.overwrite)

    cache = load_prepared_cache(args.prepared_cache)
    adaptation_indices = normalize_split_indices(
        cache["splits"]["adaptation"]
    )
    if args.limit is not None:
        adaptation_indices = adaptation_indices[: args.limit]

    if not adaptation_indices:
        raise RuntimeError("The adaptation partition is empty.")

    labels_by_property = {
        property_name: cache["labels"][property_name][
            torch.tensor(adaptation_indices, dtype=torch.long)
        ].to(torch.long)
        for property_name in PROPERTIES
    }

    for property_name, labels in labels_by_property.items():
        LOGGER.info(
            "Adaptation labels %s: positive=%d negative=%d",
            property_name,
            int(labels.sum().item()),
            int(labels.numel() - labels.sum().item()),
        )

    device = resolve_device(args.device)
    model_dtype = resolve_dtype(args.dtype, device)
    storage_dtype = resolve_dtype(
        args.storage_dtype,
        torch.device("cpu"),
    )

    model = load_model(
        model_name=args.model_name,
        device=device,
        dtype=model_dtype,
        trust_remote_code=args.trust_remote_code,
        low_cpu_mem_usage=not args.disable_low_cpu_memory,
    )

    layer_count = infer_transformer_layer_count(model)
    if args.top_k_layers > layer_count:
        LOGGER.warning(
            "top-k-layers=%d exceeds model layer count=%d; using %d.",
            args.top_k_layers,
            layer_count,
            layer_count,
        )
        args.top_k_layers = layer_count

    tokenizer_info = cache.get("tokenizer", {})
    pad_token_id = tokenizer_info.get("pad_token_id")
    if pad_token_id is None:
        pad_token_id = getattr(model.config, "pad_token_id", None)
    if pad_token_id is None:
        pad_token_id = getattr(model.config, "eos_token_id", None)
    if pad_token_id is None:
        raise RuntimeError(
            "Could not determine a padding token ID from the cache or model."
        )
    pad_token_id = int(pad_token_id)

    LOGGER.info(
        "First inference pass: extracting all %d transformer layers.",
        layer_count,
    )
    all_layer_activations = extract_activations(
        model=model,
        cache=cache,
        dataset_indices=adaptation_indices,
        batch_size=args.batch_size,
        pad_token_id=pad_token_id,
        device=device,
        pooling=args.pooling,
        selected_layers=None,
        storage_dtype=storage_dtype,
    )

    class_weight = (
        None if args.class_weight == "none" else args.class_weight
    )
    probe_results = analyze_all_layers(
        activations=all_layer_activations,
        labels_by_property=labels_by_property,
        validation_fraction=args.probe_validation_fraction,
        seed=args.seed,
        max_iter=args.probe_max_iter,
        class_weight=class_weight,
    )

    selected_layers = select_layers(
        results=probe_results,
        top_k=args.top_k_layers,
        minimum_balanced_accuracy=args.minimum_balanced_accuracy,
    )

    LOGGER.info("Selected layers:")
    for property_name in PROPERTIES:
        LOGGER.info(
            "  %s: %s",
            property_name,
            selected_layers[property_name],
        )

    union_selected_layers = sorted(
        {
            layer
            for property_layers in selected_layers.values()
            for layer in property_layers
        }
    )

    if args.skip_second_pass:
        LOGGER.info(
            "Second inference pass skipped; reusing selected all-layer tensors."
        )
        selected_layer_activations = {
            layer: all_layer_activations[layer]
            for layer in union_selected_layers
        }
    else:
        LOGGER.info(
            "Second inference pass: extracting selected layers %s.",
            union_selected_layers,
        )
        selected_layer_activations = extract_activations(
            model=model,
            cache=cache,
            dataset_indices=adaptation_indices,
            batch_size=args.batch_size,
            pad_token_id=pad_token_id,
            device=device,
            pooling=args.pooling,
            selected_layers=union_selected_layers,
            storage_dtype=storage_dtype,
        )

    probe_lookup = {
        (item.property_name, item.layer): item
        for item in probe_results
    }

    centroids, centroid_statistics, discovery = construct_centroids(
        selected_activations=selected_layer_activations,
        labels_by_property=labels_by_property,
        selected_layers=selected_layers,
        minimum_probe_balanced_accuracy=args.minimum_balanced_accuracy,
        probe_lookup=probe_lookup,
    )

    config = {
        "prepared_cache": str(args.prepared_cache),
        "prepared_cache_sha256": stable_hash(args.prepared_cache),
        "model_name": args.model_name,
        "device": str(device),
        "model_dtype": str(model_dtype).replace("torch.", ""),
        "storage_dtype": str(storage_dtype).replace("torch.", ""),
        "batch_size": args.batch_size,
        "pooling": args.pooling,
        "top_k_layers": args.top_k_layers,
        "probe_validation_fraction": args.probe_validation_fraction,
        "minimum_balanced_accuracy": args.minimum_balanced_accuracy,
        "probe_max_iter": args.probe_max_iter,
        "class_weight": class_weight,
        "skip_second_pass": args.skip_second_pass,
        "adaptation_instance_count": len(adaptation_indices),
        "layer_count": layer_count,
        "layer_numbering": "zero-based transformer block output",
        "seed": args.seed,
        "script_sha256": stable_hash(Path(__file__)),
    }

    save_outputs(
        output_dir=args.output_dir,
        cache=cache,
        adaptation_indices=adaptation_indices,
        all_layer_activations=all_layer_activations,
        selected_layer_activations=selected_layer_activations,
        selected_layers=selected_layers,
        probe_results=probe_results,
        centroids=centroids,
        centroid_statistics=centroid_statistics,
        discovery=discovery,
        config=config,
    )

    LOGGER.info("Activation discovery completed.")
    LOGGER.info("Results saved to %s", args.output_dir)
    for property_name in PROPERTIES:
        LOGGER.info(
            "%s: layers=%s representation_found=%s",
            property_name,
            selected_layers[property_name],
            discovery[property_name]["distinguishable_representation_found"],
        )

    del model
    gc.collect()
    if device.type == "cuda":
        torch.cuda.empty_cache()
    elif device.type == "mps":
        torch.mps.empty_cache()

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
