def save_layer_analysis_csv(
    path: Path,
    results: Sequence[ProbeMetrics],
) -> None:
    rows = [asdict(item) for item in results]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def save_outputs(
    output_dir: Path,
    cache: Mapping[str, Any],
    adaptation_indices: Sequence[int],
    all_layer_activations: Mapping[int, torch.Tensor],
    selected_layer_activations: Mapping[int, torch.Tensor],
    selected_layers: Mapping[str, Sequence[int]],
    probe_results: Sequence[ProbeMetrics],
    centroids: Mapping[str, Mapping[int, torch.Tensor]],
    centroid_statistics: Sequence[CentroidStatistics],
    discovery: Mapping[str, Any],
    config: Mapping[str, Any],
) -> None:
    adaptation_instance_ids = [
        cache["instance_ids"][index] for index in adaptation_indices
    ]

    torch.save(
        {
            "format_version": 1,
            "instance_ids": adaptation_instance_ids,
            "source_indices": torch.tensor(
                adaptation_indices, dtype=torch.long
            ),
            "pooling": config["pooling"],
            "layer_numbering": "zero-based transformer block output",
            "activations": dict(all_layer_activations),
        },
        output_dir / "all_layer_activations.pt",
    )

    torch.save(
        {
            "format_version": 1,
            "instance_ids": adaptation_instance_ids,
            "source_indices": torch.tensor(
                adaptation_indices, dtype=torch.long
            ),
            "pooling": config["pooling"],
            "selected_layers_by_property": {
                key: list(value) for key, value in selected_layers.items()
            },
            "activations": dict(selected_layer_activations),
        },
        output_dir / "selected_layer_activations.pt",
    )

    centroid_payload = {
        "format_version": 1,
        "model_name": config["model_name"],
        "pooling": config["pooling"],
        "layer_numbering": "zero-based transformer block output",
        "selected_layers": {
            key: list(value) for key, value in selected_layers.items()
        },
        "centroids": {
            property_name: {
                int(layer): tensor.detach().cpu().to(torch.float32)
                for layer, tensor in property_centroids.items()
            }
            for property_name, property_centroids in centroids.items()
        },
        "positive_counts": {
            property_name: int(
                cache["labels"][property_name][
                    torch.tensor(adaptation_indices, dtype=torch.long)
                ].sum().item()
            )
            for property_name in PROPERTIES
        },
        "discovery": dict(discovery),
    }
    torch.save(centroid_payload, output_dir / "property_centroids.pt")

    selected_json = {
        "layer_numbering": "zero-based transformer block output",
        "selected_layers": {
            key: list(value) for key, value in selected_layers.items()
        },
        "discovery": dict(discovery),
    }
    write_json(output_dir / "selected_layers.json", selected_json)

    probe_rows = [asdict(item) for item in probe_results]
    write_json(output_dir / "layer_analysis.json", probe_rows)
    write_json(output_dir / "activation_probe_results.json", probe_rows)
    save_layer_analysis_csv(
        output_dir / "layer_analysis.csv",
        probe_results,
    )

    write_json(
        output_dir / "centroid_statistics.json",
        [asdict(item) for item in centroid_statistics],
    )
    write_json(output_dir / "discovery_config.json", dict(config))


