def make_batch(
    input_ids_list: Sequence[torch.Tensor],
    attention_mask_list: Sequence[torch.Tensor],
    indices: Sequence[int],
    pad_token_id: int,
    device: torch.device,
) -> Tuple[torch.Tensor, torch.Tensor]:
    ids = [input_ids_list[index].to(torch.long) for index in indices]
    masks = [attention_mask_list[index].to(torch.long) for index in indices]

    padded_ids = pad_sequence(
        ids,
        batch_first=True,
        padding_value=pad_token_id,
    )
    padded_masks = pad_sequence(
        masks,
        batch_first=True,
        padding_value=0,
    )
    return padded_ids.to(device), padded_masks.to(device)


def pool_hidden_state(
    hidden_state: torch.Tensor,
    attention_mask: torch.Tensor,
    pooling: str,
) -> torch.Tensor:
    """
    Convert [batch, sequence, hidden] to [batch, hidden].

    last-token:
        Uses the final non-padding prompt token.

    mean:
        Mean over non-padding prompt tokens.

    first-token:
        Uses token position zero.
    """
    if hidden_state.ndim != 3:
        raise ValueError(
            f"Expected hidden state [B, T, H], got {tuple(hidden_state.shape)}"
        )

    if pooling == "last-token":
        lengths = attention_mask.sum(dim=1).clamp(min=1) - 1
        batch_indices = torch.arange(
            hidden_state.size(0), device=hidden_state.device
        )
        return hidden_state[batch_indices, lengths]

    if pooling == "mean":
        mask = attention_mask.unsqueeze(-1).to(hidden_state.dtype)
        numerator = (hidden_state * mask).sum(dim=1)
        denominator = mask.sum(dim=1).clamp(min=1.0)
        return numerator / denominator

    if pooling == "first-token":
        return hidden_state[:, 0, :]

    raise ValueError(f"Unsupported pooling method: {pooling}")


@torch.inference_mode()
def extract_activations(
    model: torch.nn.Module,
    cache: Mapping[str, Any],
    dataset_indices: Sequence[int],
    batch_size: int,
    pad_token_id: int,
    device: torch.device,
    pooling: str,
    selected_layers: Optional[Sequence[int]] = None,
    storage_dtype: torch.dtype = torch.float32,
) -> Dict[int, torch.Tensor]:
    """
    Extract pooled activations for all requested instances.

    Hugging Face causal language models return:
        hidden_states[0]     embedding output
        hidden_states[i + 1] transformer layer i output

    This function exposes transformer layers using zero-based numbering.
    """
    layer_count = infer_transformer_layer_count(model)
    if selected_layers is None:
        requested_layers = list(range(layer_count))
    else:
        requested_layers = sorted(set(int(layer) for layer in selected_layers))

    for layer in requested_layers:
        if layer < 0 or layer >= layer_count:
            raise IndexError(
                f"Layer {layer} is outside valid range [0, {layer_count - 1}]."
            )

    collected: Dict[int, List[torch.Tensor]] = {
        layer: [] for layer in requested_layers
    }

    total_batches = math.ceil(len(dataset_indices) / batch_size)
    for batch_number, start in enumerate(
        range(0, len(dataset_indices), batch_size), start=1
    ):
        batch_indices = dataset_indices[start : start + batch_size]
        input_ids, attention_mask = make_batch(
            cache["input_ids"],
            cache["attention_masks"],
            batch_indices,
            pad_token_id,
            device,
        )

        outputs = model(
            input_ids=input_ids,
            attention_mask=attention_mask,
            output_hidden_states=True,
            use_cache=False,
            return_dict=True,
        )

        hidden_states = outputs.hidden_states
        if hidden_states is None:
            raise RuntimeError("Model did not return hidden states.")
        if len(hidden_states) != layer_count + 1:
            raise RuntimeError(
                f"Expected {layer_count + 1} hidden-state tensors, "
                f"received {len(hidden_states)}."
            )

        for layer in requested_layers:
            pooled = pool_hidden_state(
                hidden_states[layer + 1],
                attention_mask,
                pooling,
            )
            collected[layer].append(
                pooled.detach().to("cpu", dtype=storage_dtype)
            )

        del outputs, hidden_states, input_ids, attention_mask
        if device.type == "cuda":
            torch.cuda.empty_cache()
        elif device.type == "mps":
            torch.mps.empty_cache()

        if batch_number % 25 == 0 or batch_number == total_batches:
            LOGGER.info(
                "Activation extraction: batch %d/%d (%d/%d instances)",
                batch_number,
                total_batches,
                min(start + batch_size, len(dataset_indices)),
                len(dataset_indices),
            )

    result = {
        layer: torch.cat(chunks, dim=0)
        for layer, chunks in collected.items()
    }

    expected = len(dataset_indices)
    for layer, tensor in result.items():
        if tensor.size(0) != expected:
            raise RuntimeError(
                f"Layer {layer} produced {tensor.size(0)} rows; expected {expected}."
            )

    return result


