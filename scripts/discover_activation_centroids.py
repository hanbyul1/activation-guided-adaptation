def stratified_probe_indices(
    labels: np.ndarray,
    validation_fraction: float,
    seed: int,
) -> Tuple[np.ndarray, np.ndarray]:
    if labels.ndim != 1:
        raise ValueError("Labels must be one-dimensional.")

    counts = np.bincount(labels.astype(np.int64), minlength=2)
    if counts.min() < 2:
        raise ValueError(
            "Both classes require at least two instances for probe validation; "
            f"class counts={counts.tolist()}."
        )

    splitter = StratifiedShuffleSplit(
        n_splits=1,
        test_size=validation_fraction,
        random_state=seed,
    )
    dummy = np.zeros((labels.shape[0], 1), dtype=np.float32)
    train_idx, validation_idx = next(splitter.split(dummy, labels))
    return train_idx, validation_idx


def centroid_metrics(
    activations: np.ndarray,
    labels: np.ndarray,
) -> Tuple[float, float, float]:
    positive = activations[labels == 1]
    negative = activations[labels == 0]

    positive_centroid = positive.mean(axis=0)
    negative_centroid = negative.mean(axis=0)

    distance = float(np.linalg.norm(positive_centroid - negative_centroid))

    positive_norm = np.linalg.norm(positive_centroid)
    negative_norm = np.linalg.norm(negative_centroid)
    denominator = max(positive_norm * negative_norm, 1e-12)
    centroid_cosine = float(
        np.dot(positive_centroid, negative_centroid) / denominator
    )
    cosine_separation = 1.0 - centroid_cosine

    positive_variance = float(
        np.mean(np.sum((positive - positive_centroid) ** 2, axis=1))
    )
    negative_variance = float(
        np.mean(np.sum((negative - negative_centroid) ** 2, axis=1))
    )
    within_variance = max(positive_variance + negative_variance, 1e-12)
    fisher_ratio = float(distance * distance / within_variance)

    return distance, cosine_separation, fisher_ratio


def analyze_one_layer(
    property_name: str,
    layer: int,
    activations: torch.Tensor,
    labels: torch.Tensor,
    validation_fraction: float,
    seed: int,
    max_iter: int,
    class_weight: Optional[str],
) -> ProbeMetrics:
    x = activations.detach().cpu().numpy().astype(np.float64, copy=False)

    if not np.isfinite(x).all():
        raise FloatingPointError(
            f"{property_name} layer {layer} contains NaN or infinite activations."
        )
    y = labels.detach().cpu().numpy().astype(np.int64, copy=False)

    train_idx, validation_idx = stratified_probe_indices(
        y,
        validation_fraction=validation_fraction,
        seed=seed,
    )

    scaler = StandardScaler()
    x_train = scaler.fit_transform(x[train_idx])
    x_validation = scaler.transform(x[validation_idx])

    classifier = LogisticRegression(
        max_iter=max_iter,
        class_weight=class_weight,
        solver="liblinear",
        random_state=seed,
    )
    classifier.fit(x_train, y[train_idx])

    predictions = classifier.predict(x_validation)
    probabilities = classifier.predict_proba(x_validation)[:, 1]

    try:
        auc: Optional[float] = safe_float(
            roc_auc_score(y[validation_idx], probabilities)
        )
    except ValueError:
        auc = None

    distance, cosine_separation, fisher_ratio = centroid_metrics(x, y)

    balanced = safe_float(
        balanced_accuracy_score(y[validation_idx], predictions)
    )
    f1 = safe_float(
        f1_score(y[validation_idx], predictions, zero_division=0)
    )

    # The primary selection signal is validation performance. Fisher separation
    # contributes a bounded secondary term so scale differences cannot dominate.
    bounded_fisher = fisher_ratio / (1.0 + fisher_ratio)
    composite = 0.50 * balanced + 0.35 * (auc if auc is not None else 0.5)
    composite += 0.15 * bounded_fisher

    return ProbeMetrics(
        property_name=property_name,
        layer=layer,
        train_size=int(len(train_idx)),
        validation_size=int(len(validation_idx)),
        positive_train=int(y[train_idx].sum()),
        positive_validation=int(y[validation_idx].sum()),
        accuracy=safe_float(
            accuracy_score(y[validation_idx], predictions)
        ),
        balanced_accuracy=balanced,
        precision=safe_float(
            precision_score(y[validation_idx], predictions, zero_division=0)
        ),
        recall=safe_float(
            recall_score(y[validation_idx], predictions, zero_division=0)
        ),
        f1=f1,
        roc_auc=auc,
        centroid_distance=safe_float(distance),
        cosine_separation=safe_float(cosine_separation),
        fisher_ratio=safe_float(fisher_ratio),
        composite_score=safe_float(composite),
    )


def analyze_all_layers(
    activations: Mapping[int, torch.Tensor],
    labels_by_property: Mapping[str, torch.Tensor],
    validation_fraction: float,
    seed: int,
    max_iter: int,
    class_weight: Optional[str],
) -> List[ProbeMetrics]:
    results: List[ProbeMetrics] = []

    for property_offset, property_name in enumerate(PROPERTIES):
        labels = labels_by_property[property_name]
        positive_count = int(labels.sum().item())
        negative_count = int(labels.numel() - positive_count)
        LOGGER.info(
            "Analyzing property=%s positives=%d negatives=%d",
            property_name,
            positive_count,
            negative_count,
        )

        if positive_count < 2 or negative_count < 2:
            raise RuntimeError(
                f"Insufficient class support for {property_name}: "
                f"positive={positive_count}, negative={negative_count}."
            )

        for layer in sorted(activations):
            metrics = analyze_one_layer(
                property_name=property_name,
                layer=layer,
                activations=activations[layer],
                labels=labels,
                validation_fraction=validation_fraction,
                seed=seed + property_offset,
                max_iter=max_iter,
                class_weight=class_weight,
            )
            results.append(metrics)
            LOGGER.info(
                "%s layer=%d balanced_acc=%.4f auc=%s f1=%.4f score=%.4f",
                property_name,
                layer,
                metrics.balanced_accuracy,
                (
                    f"{metrics.roc_auc:.4f}"
                    if metrics.roc_auc is not None
                    else "NA"
                ),
                metrics.f1,
                metrics.composite_score,
            )

    return results


def select_layers(
    results: Sequence[ProbeMetrics],
    top_k: int,
    minimum_balanced_accuracy: float,
) -> Dict[str, List[int]]:
    selected: Dict[str, List[int]] = {}

    for property_name in PROPERTIES:
        property_results = [
            item for item in results if item.property_name == property_name
        ]
        ranked = sorted(
            property_results,
            key=lambda item: (
                item.composite_score,
                item.balanced_accuracy,
                item.roc_auc if item.roc_auc is not None else -1.0,
                item.f1,
                item.layer,
            ),
            reverse=True,
        )

        eligible = [
            item
            for item in ranked
            if item.balanced_accuracy >= minimum_balanced_accuracy
        ]

        if not eligible:
            LOGGER.warning(
                "No %s layer met minimum balanced accuracy %.3f; "
                "falling back to the highest-scoring layer.",
                property_name,
                minimum_balanced_accuracy,
            )
            eligible = ranked[:1]

        selected[property_name] = [
            item.layer for item in eligible[:top_k]
        ]

    return selected


