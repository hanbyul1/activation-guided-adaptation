def load_prepared_cache(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"Prepared cache does not exist: {path}")

    LOGGER.info("Loading prepared dataset cache: %s", path)
    cache = torch.load(path, map_location="cpu", weights_only=False)

    required = {
        "instance_ids",
        "input_ids",
        "attention_masks",
        "labels",
        "splits",
    }
    missing = required - set(cache)
    if missing:
        raise KeyError(
            "Prepared cache is missing required keys: "
            + ", ".join(sorted(missing))
        )

    count = len(cache["instance_ids"])
    for key in ("input_ids", "attention_masks"):
        if len(cache[key]) != count:
            raise ValueError(
                f"Cache length mismatch: {key} has {len(cache[key])}, "
                f"expected {count}."
            )

    for property_name in PROPERTIES:
        if property_name not in cache["labels"]:
            raise KeyError(f"Missing label tensor: {property_name}")
        if len(cache["labels"][property_name]) != count:
            raise ValueError(f"Label length mismatch for {property_name}.")

    if "adaptation" not in cache["splits"]:
        raise KeyError("The cache must contain an 'adaptation' split.")

    return cache


def normalize_split_indices(value: Any) -> List[int]:
    if isinstance(value, torch.Tensor):
        return [int(item) for item in value.tolist()]
    return [int(item) for item in value]


