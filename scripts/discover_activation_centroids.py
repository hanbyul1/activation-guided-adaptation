def construct_centroids(
    selected_activations: Mapping[int, torch.Tensor],
    labels_by_property: Mapping[str, torch.Tensor],
    selected_layers: Mapping[str, Sequence[int]],
    minimum_probe_balanced_accuracy: float,
    probe_lookup: Mapping[Tuple[str, int], ProbeMetrics],
) -> Tuple[Dict[str, Dict[int, torch.Tensor]], List[CentroidStatistics], Dict[str, Any]]:
    centroids: Dict[str, Dict[int, torch.Tensor]] = {}
    statistics: List[CentroidStatistics] = []
    discovery: Dict[str, Any] = {}

    for property_name in PROPERTIES:
        labels = labels_by_property[property_name].to(torch.long)
        positive_mask = labels == 1
        negative_mask = labels == 0

        property_centroids: Dict[int, torch.Tensor] = {}
        qualifying_layers = 0

        for layer in selected_layers[property_name]:
            activations = selected_activations[layer].to(torch.float32)
            positive = activations[positive_mask]
            negative = activations[negative_mask]

            if positive.size(0) == 0:
                raise RuntimeError(
                    f"Cannot construct {property_name} centroid at layer {layer}: "
                    "no positive instances."
                )

            positive_centroid = positive.mean(dim=0)
            negative_centroid = negative.mean(dim=0)
            property_centroids[layer] = positive_centroid

            centroid_distance = torch.linalg.vector_norm(
                positive_centroid - negative_centroid
            )
            centroid_cosine = F.cosine_similarity(
                positive_centroid.unsqueeze(0),
                negative_centroid.unsqueeze(0),
                dim=1,
            )[0]

            positive_distance = torch.linalg.vector_norm(
                positive - positive_centroid.unsqueeze(0),
                dim=1,
            ).mean()
            negative_distance = torch.linalg.vector_norm(
                negative - positive_centroid.unsqueeze(0),
                dim=1,
            ).mean()

            statistics.append(
                CentroidStatistics(
                    property_name=property_name,
                    layer=layer,
                    positive_count=int(positive.size(0)),
                    negative_count=int(negative.size(0)),
                    hidden_dimension=int(activations.size(1)),
                    positive_mean_norm=safe_float(
                        torch.linalg.vector_norm(positive, dim=1).mean().item()
                    ),
                    negative_mean_norm=safe_float(
                        torch.linalg.vector_norm(negative, dim=1).mean().item()
                    ),
                    centroid_distance=safe_float(centroid_distance.item()),
                    centroid_cosine_similarity=safe_float(centroid_cosine.item()),
                    positive_mean_distance_to_centroid=safe_float(
                        positive_distance.item()
                    ),
                    negative_mean_distance_to_positive_centroid=safe_float(
                        negative_distance.item()
                    ),
                )
            )

            metrics = probe_lookup[(property_name, layer)]
            if metrics.balanced_accuracy >= minimum_probe_balanced_accuracy:
                qualifying_layers += 1

        centroids[property_name] = property_centroids
        discovery[property_name] = {
            "distinguishable_representation_found": qualifying_layers > 0,
            "qualifying_selected_layers": qualifying_layers,
            "selected_layer_count": len(selected_layers[property_name]),
            "criterion": (
                "At least one selected layer has probe balanced accuracy "
                f">= {minimum_probe_balanced_accuracy:.3f}."
            ),
        }

    return centroids, statistics, discovery


