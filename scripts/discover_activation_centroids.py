#!/usr/bin/env python3
"""
discover_activation_centroids.py

Purpose
-------
Discover target-property activation representations and construct layer-specific
activation centroids for the three SWE-bench properties prepared by
prepare_dataset_and_labels.py:

    1. coupling
    2. complexity
    3. modularity

The script combines the following experimental stages:

    1. Load the prepared SWE-bench adaptation partition.
    2. Run the pretrained StarCoderBase model and extract pooled hidden
       representations from all transformer layers.
    3. Perform preliminary layer analysis to identify layers that contain the
       strongest target-property signal.
    4. Select the top-performing layers independently for each property.
    5. Optionally perform a second inference pass that stores activations only
       for the selected layers.
    6. Evaluate whether positive and negative instances form distinguishable
       activation representations using a standardized linear probe.
    7. Construct a layer-specific positive activation centroid for each target
       property.
    8. Save all activations, layer scores, probe results, selected layers, and
       centroids for subsequent activation-guided LoRA adaptation.

Expected input
--------------
outputs/prepared_swebench/prepared_dataset.pt

This input is generated by prepare_dataset_and_labels.py and must contain:

    input_ids
    attention_masks
    instance_ids
    labels
    splits

Example
-------
python discover_activation_centroids.py \
    --prepared-cache outputs/prepared_swebench/prepared_dataset.pt \
    --model-name bigcode/starcoderbase-1b \
    --output-dir outputs/activation_centroids \
    --batch-size 1 \
    --top-k-layers 4 \
    --pooling last-token \
    --dtype float16

CPU example
-----------
python discover_activation_centroids.py \
    --prepared-cache outputs/prepared_swebench/prepared_dataset.pt \
    --model-name bigcode/starcoderbase-1b \
    --output-dir outputs/activation_centroids \
    --device cpu \
    --dtype float32 \
    --batch-size 1

Outputs
-------
<output-dir>/
    all_layer_activations.pt
    selected_layer_activations.pt
    selected_layers.json
    layer_analysis.csv
    layer_analysis.json
    activation_probe_results.json
    property_centroids.pt
    centroid_statistics.json
    discovery_config.json

Methodological decisions
------------------------
* Hidden states are pooled independently for each benchmark instance.
* By default, the final non-padding prompt token is used.
* Layer selection is performed only on the adaptation partition.
* Each property is analyzed independently because labels are multi-label.
* A linear probe is used only as an analysis instrument. Its parameters are not
  used during LoRA adaptation.
* Positive centroids are computed only from positively labeled adaptation
  instances.
* The embedding output is excluded by default; transformer block outputs are
  numbered from 0 to num_hidden_layers - 1.
"""

